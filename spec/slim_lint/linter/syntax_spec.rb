# frozen_string_literal: true

require 'spec_helper'

describe SlimLint::Linter::Syntax do
  include_context 'linter'

  [
    '',
    'p Hello world',
    "- # A Ruby control comment\n= 1 + 1\n",
    "= yield\n",
    "= capture do\n  = missing_helper\n",
    "ruby:\n  value = 1\n= value\n",
    "= form_for(object) do |f|\n  = render 'fields', f:\n" \
    "  - content_for :footer do\n    p Footer\n",
    "= raise 'Templates must not be executed'\n",
  ].each do |source|
    context "with valid source #{source.inspect}" do
      let(:slim) { source }

      it { should_not report_lint }
    end
  end

  context 'with a trailing Ruby comment in output code' do
    let(:slim) { "' Hello. This is some simple math:\n= 1 + 1 # this equals 2\n" }

    it { should report_lint line: 2, count: 1 }

    it 'reports an error explaining that compilation produced invalid Ruby' do
      expect(subject.lints.first).to be_error
      expect(subject.lints.first.message).to include('Invalid Ruby generated by Slim:')
    end
  end

  context 'with invalid output code before more markup' do
    let(:slim) { "p Before\n= (1 +\np After\n" }

    it { should report_lint line: 2, count: 1 }
  end

  context 'with code after multiline text' do
    let(:slim) { "- if visible?\n  | First\n    second\n    third\n  = (1 +\n" }

    it { should report_lint line: 5, count: 1 }
  end

  context 'with a fatal Ruby syntax error' do
    let(:slim) { '= "unterminated' }

    it { should report_lint line: 1, count: 1 }

    it 'can check another document after the error' do
      document = SlimLint::Document.new('p Valid', config: config)
      expect(subject.run(document)).to be_empty
    end
  end

  context 'with a Slim compilation error' do
    let(:slim) { 'a href="first" href="second"' }

    it 'reports the compiler error without crashing' do
      expect(subject.lints.first).to be_error
      expect(subject.lints.first.message).to include('Multiple href attributes specified')
    end
  end

  context 'with syntax checking disabled for the offending line' do
    let(:slim) { "/ slim-lint:disable Syntax\n= 1 + 1 # comment\n" }

    it { should_not report_lint }
  end
end
